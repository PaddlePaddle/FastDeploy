"""import ops"""
import functools
import importlib
import inspect
import os
import re
import sys

import paddle

from fastdeploy.utils import llm_logger as logger

# Cached list of op names from fastdeploy_ops_pd_.so.
# Populated on first load, reused for subsequent calls.
_PD_OP_NAMES = None


def import_custom_ops(package, module_name, global_ns):
    """
    Imports custom operations from a specified module within a package and adds them to a global namespace.

    Args:
        package (str): The name of the package containing the module.
        module_name (str): The name of the module within the package.
        global_ns (dict): The global namespace to add the imported functions to.
    """
    # Load custom ops from fastdeploy_ops_pd_.so (DeepGEMM build).
    # This .so contains all ops including get_token_penalty_multi_scores,
    # gptq_marlin_repack, etc.
    pd_loaded = _load_pd_ops(package, global_ns)

    if not pd_loaded:
        # pd_.so not available — fallback to fastdeploy_ops.so if it exists
        try:
            module = importlib.import_module(module_name, package=package)
            functions = inspect.getmembers(module)
            for func_name, func in functions:
                if func_name.startswith("__") or func_name == "_C_ops":
                    continue
                logger.debug(f"Import {func_name} from {package}")
                try:
                    global_ns[func_name] = func
                except Exception as e:
                    logger.warning(f"Failed to import op {func_name}: {e}")

        except Exception as e:
            logger.warning(f"Ops of {package} import failed, it may be not compiled. {e}")

    preprocess_static_op(global_ns)


def _extract_op_names_from_py(pd_so_path):
    """Extract op names from the companion fastdeploy_ops.py file.

    The .py file (generated by PaddlePaddle's build system) contains Python
    wrapper functions named static_op_* that call _C_ops._run_custom_op().
    We extract these names to know which ops to create wrappers for.
    """
    try:
        py_path = os.path.join(os.path.dirname(pd_so_path), 'fastdeploy_ops.py')
        if os.path.exists(py_path):
            op_names = []
            with open(py_path, 'r') as f:
                for line in f:
                    m = re.match(r'^def (static_op_\w+)\(', line)
                    if m:
                        op_names.append(m.group(1))
            if op_names:
                logger.debug(f"Extracted {len(op_names)} op names from {py_path}")
                return op_names
    except Exception as e:
        logger.debug(f"Failed to extract op names from .py: {e}")
    return []


def _find_pd_so(package):
    """Find fastdeploy_ops_pd_.so in various locations."""
    pkg_path = package.replace('.', '/')
    curdir = os.path.dirname(os.path.abspath(__file__))
    fd_root = os.path.join(curdir, '..')  # FastDeploy root

    search_dirs = [
        # Installed location: next to fastdeploy_ops.py/fastdeploy_ops.so
        os.path.join(fd_root, pkg_path),
        # Source location: custom_ops/third_party/DeepGEMM/
        os.path.join(fd_root, 'custom_ops', 'third_party', 'DeepGEMM'),
        # Source location: custom_ops/
        os.path.join(fd_root, 'custom_ops'),
    ]

    for search_dir in search_dirs:
        if not os.path.isdir(search_dir):
            continue
        # Check directly in the directory
        candidate = os.path.join(search_dir, 'fastdeploy_ops_pd_.so')
        if os.path.exists(candidate):
            return candidate
        # Check in versioned subdirectories (e.g., fastdeploy_ops_80/)
        for entry in os.listdir(search_dir):
            entry_path = os.path.join(search_dir, entry)
            if os.path.isdir(entry_path) and entry.startswith('fastdeploy_ops'):
                candidate = os.path.join(entry_path, 'fastdeploy_ops_pd_.so')
                if os.path.exists(candidate):
                    return candidate
    return None


def _load_pd_ops(package, global_ns):
    """Load custom ops from fastdeploy_ops_pd_.so.

    Returns True if ops were loaded successfully, False otherwise.
    """
    pd_so_path = _find_pd_so(package)
    if pd_so_path is None:
        logger.debug("fastdeploy_ops_pd_.so not found, skipping")
        return False

    # Check if ops are already available
    if global_ns.get('get_token_penalty_multi_scores') is not None:
        logger.debug("PD ops already available, skipping load")
        return True

    try:
        # Prevent fastdeploy_ops.py from being imported during pd_.so loading.
        # If fastdeploy_ops.py is imported, its __bootstrap__() will try to
        # load fastdeploy_ops_pd_.so again, causing op registration conflicts.
        _block_bootstrap()

        # Load the .so and register ops with PaddlePaddle.
        # Note: load_op_meta_info_and_register_op returns ops registered in THIS
        # call only. If another module already loaded this .so, it returns empty.
        # We always call it to ensure ops are registered, even if already loaded.
        paddle.utils.cpp_extension.load_op_meta_info_and_register_op(pd_so_path)

        # Create wrappers for all known op names, regardless of return value.
        # The _PD_OP_NAMES list is populated on first load and reused for
        # subsequent calls.
        global _PD_OP_NAMES
        if _PD_OP_NAMES is None:
            _PD_OP_NAMES = _extract_op_names_from_py(pd_so_path)

        added = 0
        for op_name in _PD_OP_NAMES:
            short_name = op_name.removeprefix("static_op_")
            if short_name not in global_ns:
                global_ns[short_name] = _make_op_fn(op_name)
                added += 1
            if op_name not in global_ns:
                global_ns[op_name] = _make_op_fn(op_name)

        logger.info(f"Loaded {len(_PD_OP_NAMES)} ops from {pd_so_path}, added {added} wrappers for {package}")
        return True

    except Exception as e:
        logger.warning(f"Failed to load fastdeploy_ops_pd_.so: {e}")
        return False
    finally:
        _unblock_bootstrap()


def _make_op_fn(op_name):
    """Create a wrapper function that calls a registered PaddlePaddle custom op."""
    def _op_fn(*args, **kwargs):
        return paddle._C_ops._run_custom_op(op_name, *args, **kwargs)
    return _op_fn


_PD_BOOTSTRAP_BLOCKED = False


def _block_bootstrap():
    """Prevent fastdeploy_ops.py's __bootstrap__() from running during import."""
    global _PD_BOOTSTRAP_BLOCKED
    _PD_BOOTSTRAP_BLOCKED = True
    class _DummyOpsModule:
        pass
    sys.modules['fastdeploy.model_executor.ops.gpu.fastdeploy_ops_80.fastdeploy_ops'] = _DummyOpsModule()


def _unblock_bootstrap():
    """Remove the dummy module block."""
    global _PD_BOOTSTRAP_BLOCKED
    _PD_BOOTSTRAP_BLOCKED = False
    key = 'fastdeploy.model_executor.ops.gpu.fastdeploy_ops_80.fastdeploy_ops'
    mod = sys.modules.get(key)
    if mod is not None and mod.__class__.__name__ == '_DummyOpsModule':
        del sys.modules[key]


def rename_imported_op(old_name, new_name, global_ns):
    """
    Renames an imported operation in the global namespace.

    Args:
        old_name (str): The original name of the operation in the global namespace.
        new_name (str): The new name to be given to the operation.
        global_ns (dict): The global namespace where the operation is stored.
    """
    if old_name not in global_ns:
        return
    global_ns[new_name] = global_ns[old_name]
    del global_ns[old_name]


def wrap_unified_op(original_cpp_ext_op, original_custom_op):
    """
    Wrap a static operator into a unified operator with runtime dispatching.
    Args:
        original_cpp_ext_op: Original C++ extension operator function.
        original_custom_op: Original custom operator function.
    """
    try:

        @paddle.jit.marker.unified
        @functools.wraps(original_custom_op)
        def unified_op(*args, **kwargs):
            if paddle.in_dynamic_mode():
                res = original_cpp_ext_op(*args, **kwargs)
                if res is None:
                    return None
                # TODO(DrRyanHuang): Remove this if when we align the implementation of custom op and C++ extension
                if isinstance(res, list) and len(res) == 1:
                    return res[0]
                return res
            return original_custom_op(*args, **kwargs)

    except:
        unified_op = None
        logger.warning("Paddle version not support JIT mode.")
    return unified_op


def preprocess_static_op(global_ns):
    """
    Transforms operator/function references in the global namespace based on the presence of 'static_op_' prefixes.

    Args:
        global_ns (dict): The global namespace (typically globals()) to modify.
        flag (bool): Determines transformation behavior.
    """
    static_op_prefix = "static_op_"
    static_op_names = [k for k in global_ns if k.startswith(static_op_prefix)]

    for static_op_name in static_op_names:
        op_name = static_op_name.removeprefix(static_op_prefix)
        if op_name not in global_ns:
            global_ns[op_name] = global_ns[static_op_name]
            continue

        original_cpp_ext_op = global_ns[op_name]
        original_custom_op = global_ns[static_op_name]
        global_ns[op_name] = wrap_unified_op(original_cpp_ext_op, original_custom_op)
